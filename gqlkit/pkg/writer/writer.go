// Package writer provides utilities for writing generated Go source files to
// disk. It handles directory creation, go/format formatting of generated code,
// and offers a BufferedWriter for building content incrementally before writing.
package writer

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"
)

// File modes for generated output: directories traversable by everyone,
// files world-readable. Generated code holds no secrets.
const (
	dirPerm  os.FileMode = 0o755
	filePerm os.FileMode = 0o644
)

// goModGoVersion is the `go` directive WriteGoMod emits.
const goModGoVersion = "1.21"

// GeneratedHeader is the banner WriteFileWithHeader prepends. It follows the
// `^// Code generated .* DO NOT EDIT\.$` convention so tools treat the file as
// generated.
const GeneratedHeader = BannerLine + "\n\n"

// BannerLine is the exact first line of every file gqlkit generates. Prune
// treats a file as gqlkit-owned ONLY when its first line equals this string
// byte for byte, so changing it orphans every previously generated file from
// pruning — never edit it casually.
const BannerLine = "// Code generated by gqlkit. DO NOT EDIT."

// Writer handles writing generated Go files to a configured output directory.
// It automatically creates parent directories and applies gofmt formatting.
type Writer struct {
	outputDir string          // root directory for all generated output
	written   map[string]bool // slash-separated paths written via WriteFile
}

// NewWriter returns a Writer rooted at outputDir. Nothing is created on disk
// until a write or EnsureDir; every filename passed to the Writer is joined
// onto outputDir.
func NewWriter(outputDir string) *Writer {
	return &Writer{outputDir: outputDir, written: map[string]bool{}}
}

// WriteFile writes content to a file in the output directory, automatically
// creating any intermediate directories. The content is run through go/format;
// if formatting fails, the raw content is written with a warning.
func (w *Writer) WriteFile(filename, content string) error {
	fullPath := filepath.Join(w.outputDir, filename)

	// Ensure parent directory exists (handles subdirectories like fields/, queries/, mutations/)
	parentDir := filepath.Dir(fullPath)
	if err := os.MkdirAll(parentDir, dirPerm); err != nil {
		return fmt.Errorf("failed to create directory %s: %w", parentDir, err)
	}

	// Format Go code
	formatted, err := format.Source([]byte(content))
	if err != nil {
		// If formatting fails, write unformatted content for debugging
		fmt.Printf("Warning: failed to format %s: %v\n", filename, err)
		formatted = []byte(content)
	}

	if err := os.WriteFile(fullPath, formatted, filePerm); err != nil {
		return fmt.Errorf("failed to write file %s: %w", filename, err)
	}
	if w.written == nil { // zero-value Writer
		w.written = map[string]bool{}
	}
	w.written[filepath.ToSlash(filepath.Clean(filename))] = true

	return nil
}

// WriteGoMod writes a minimal go.mod file into the output directory.
// If modulePath is empty, packageName is used as the module path.
func (w *Writer) WriteGoMod(modulePath, packageName string) error {
	if modulePath == "" {
		modulePath = packageName
	}

	content := fmt.Sprintf("module %s\n\ngo %s\n", modulePath, goModGoVersion)

	filepath := filepath.Join(w.outputDir, "go.mod")

	if err := os.MkdirAll(w.outputDir, dirPerm); err != nil {
		return fmt.Errorf("failed to create output directory: %w", err)
	}

	if err := os.WriteFile(filepath, []byte(content), filePerm); err != nil {
		return fmt.Errorf("failed to write go.mod: %w", err)
	}

	return nil
}

// FormatGoCode gofmt-formats Go source. On a syntax error it returns the
// input unchanged together with the error, so callers can still inspect it.
func FormatGoCode(code string) (string, error) {
	formatted, err := format.Source([]byte(code))
	if err != nil {
		return code, err
	}
	return string(formatted), nil
}

// WriteFormattedFile writes formatted Go code to a file
func (w *Writer) WriteFormattedFile(filename, content string) error {
	formatted, err := FormatGoCode(content)
	if err != nil {
		return fmt.Errorf("failed to format %s: %w", filename, err)
	}

	return w.WriteFile(filename, formatted)
}

// EnsureDir creates the output directory (and parents) if missing; a no-op
// when it already exists.
func (w *Writer) EnsureDir() error {
	return os.MkdirAll(w.outputDir, dirPerm)
}

// OutputPath returns the full path for a file in the output directory
func (w *Writer) OutputPath(filename string) string {
	return filepath.Join(w.outputDir, filename)
}

// Exists checks if a file exists in the output directory
func (w *Writer) Exists(filename string) bool {
	path := filepath.Join(w.outputDir, filename)
	_, err := os.Stat(path)
	return err == nil
}

// Clean removes all files in the output directory
func (w *Writer) Clean() error {
	if _, err := os.Stat(w.outputDir); os.IsNotExist(err) {
		return nil
	}

	entries, err := os.ReadDir(w.outputDir)
	if err != nil {
		return fmt.Errorf("failed to read output directory: %w", err)
	}

	for _, entry := range entries {
		path := filepath.Join(w.outputDir, entry.Name())
		if err := os.RemoveAll(path); err != nil {
			return fmt.Errorf("failed to remove %s: %w", path, err)
		}
	}

	return nil
}

// WriteFileWithHeader writes content prefixed with GeneratedHeader.
func (w *Writer) WriteFileWithHeader(filename, content string) error {
	return w.WriteFile(filename, GeneratedHeader+content)
}

// BufferedWriter collects content in memory before writing. It implements
// io.Writer so it can be used with fmt.Fprintf and template execution.
type BufferedWriter struct {
	buffer bytes.Buffer
}

// NewBufferedWriter returns an empty BufferedWriter (the zero value is also
// ready to use).
func NewBufferedWriter() *BufferedWriter {
	return &BufferedWriter{}
}

// Write appends p to the buffer; it never returns an error (io.Writer).
func (bw *BufferedWriter) Write(p []byte) (n int, err error) {
	return bw.buffer.Write(p)
}

// WriteString appends s to the buffer; it never returns an error
// (io.StringWriter).
func (bw *BufferedWriter) WriteString(s string) (n int, err error) {
	return bw.buffer.WriteString(s)
}

// String returns the buffer content as a string
func (bw *BufferedWriter) String() string {
	return bw.buffer.String()
}

// Reset empties the buffer so the BufferedWriter can be reused.
func (bw *BufferedWriter) Reset() {
	bw.buffer.Reset()
}

// Written reports whether filename (relative to the output dir) was written
// by this Writer.
func (w *Writer) Written(filename string) bool {
	return w.written[filepath.ToSlash(filepath.Clean(filename))]
}

// maxBannerProbe bounds how much of each file Prune reads to find the first
// line; the banner is far shorter, so a longer first line cannot match.
const maxBannerProbe = 256

// Prune removes stale generated files under the output directory, then the
// subdirectories that removal leaves empty, and returns what it removed as
// slash-separated relative paths, sorted: files as "a/b.go", directories with
// a trailing slash ("mutations/").
//
// A file is removed only when ALL hold: it is a regular file (symlinks and
// special files are never touched, and symlinked directories are not
// followed), its first line is exactly BannerLine, and this Writer did not
// write it in the current run. Hand-written files therefore always survive,
// as does anything another tool generated.
//
// A directory is removed only when this prune empties it: it contained at
// least one stale file and every entry in it is a stale file or a directory
// that is itself removed. A directory that was already empty, or that holds
// anything else, is kept; the output directory itself is never removed.
//
// With dryRun the same list is returned and nothing is deleted. A missing
// output directory prunes nothing. Call it AFTER the run's writes; running it
// twice is idempotent.
func (w *Writer) Prune(dryRun bool) ([]string, error) {
	var stale []string
	err := filepath.WalkDir(w.outputDir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			if path == w.outputDir && os.IsNotExist(err) {
				return filepath.SkipDir
			}
			return err
		}
		if !d.Type().IsRegular() {
			return nil
		}
		rel, err := filepath.Rel(w.outputDir, path)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		if w.written[rel] {
			return nil
		}
		owned, err := hasBanner(path)
		if err != nil || !owned {
			return err
		}
		stale = append(stale, rel)
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("prune %s: %w", w.outputDir, err)
	}

	dirs, err := w.emptiedDirs(stale)
	if err != nil {
		return nil, fmt.Errorf("prune %s: %w", w.outputDir, err)
	}
	removed := append(append([]string{}, stale...), dirs...)
	sort.Strings(removed)
	if dryRun {
		return removed, nil
	}

	for _, rel := range stale {
		if err := os.Remove(filepath.Join(w.outputDir, filepath.FromSlash(rel))); err != nil {
			return nil, fmt.Errorf("prune %s: %w", rel, err)
		}
	}
	// Deepest first; os.Remove refuses a non-empty directory, so a file
	// that appeared since the scan makes this fail instead of deleting it.
	for i := len(dirs) - 1; i >= 0; i-- {
		if err := os.Remove(filepath.Join(w.outputDir, filepath.FromSlash(strings.TrimSuffix(dirs[i], "/")))); err != nil {
			return nil, fmt.Errorf("prune %s: %w", dirs[i], err)
		}
	}
	return removed, nil
}

// emptiedDirs returns, sorted shallowest first with a trailing slash, the
// directories (below the output dir) that removing stale would leave empty —
// see Prune for the rule.
func (w *Writer) emptiedDirs(stale []string) ([]string, error) {
	staleSet := map[string]bool{}
	candidates := map[string]bool{}
	for _, rel := range stale {
		staleSet[rel] = true
		for dir := path.Dir(rel); dir != "."; dir = path.Dir(dir) {
			candidates[dir] = true
		}
	}
	ordered := make([]string, 0, len(candidates))
	for dir := range candidates {
		ordered = append(ordered, dir)
	}
	// Deepest first, so a parent sees its children's verdicts.
	sort.Slice(ordered, func(i, j int) bool {
		di, dj := strings.Count(ordered[i], "/"), strings.Count(ordered[j], "/")
		if di != dj {
			return di > dj
		}
		return ordered[i] < ordered[j]
	})
	removable := map[string]bool{}
	for _, dir := range ordered {
		entries, err := os.ReadDir(filepath.Join(w.outputDir, filepath.FromSlash(dir)))
		if err != nil {
			return nil, err
		}
		empties := true
		for _, e := range entries {
			child := dir + "/" + e.Name()
			if !staleSet[child] && (!e.IsDir() || !removable[child]) {
				empties = false
				break
			}
		}
		if empties {
			removable[dir] = true
		}
	}
	out := make([]string, 0, len(removable))
	for dir := range removable {
		out = append(out, dir+"/")
	}
	sort.Slice(out, func(i, j int) bool {
		di, dj := strings.Count(out[i], "/"), strings.Count(out[j], "/")
		if di != dj {
			return di < dj
		}
		return out[i] < out[j]
	})
	return out, nil
}

// hasBanner reports whether the file's first line is exactly BannerLine
// (a trailing "\r" from CRLF files is tolerated).
func hasBanner(path string) (bool, error) {
	f, err := os.Open(path)
	if err != nil {
		return false, err
	}
	// Read-only handle; a Close error cannot change the probe result.
	defer func() { _ = f.Close() }()
	line, err := bufio.NewReaderSize(f, maxBannerProbe).ReadSlice('\n')
	if err != nil && len(line) == 0 {
		return false, nil // empty file, or first line longer than the probe
	}
	return string(bytes.TrimRight(line, "\r\n")) == BannerLine, nil
}
