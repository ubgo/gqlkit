// importEdgeSchema packs three "imported and not used" / "redeclared" traps,
// each the only use of its import in the package it lands in:
//
//   - Time and DateTime both bind to time.Time → scalars/ imported "time"
//     twice ("time redeclared").
//   - input In has a placeholder `_: Stamp` (skipped by skipGenField) as the
//     only scalar-typed field → inputs/ imported scalars/ for nothing.
//   - interface Lonely has no implementer and is the only type with an enum
//     field → types/ imported enums/ for a field interfaces never render.
const importEdgeSchema = `
scalar Time
scalar DateTime
scalar Stamp
enum Color { RED }
interface Lonely { c: Color }
type Ev { at: Time d: DateTime }
input In { _: Stamp x: Int }
type Query { ev: Ev n(in: In): Int }
`

const importEdgeConfig = `{ "bindings": { "DateTime": { "model": "time.Time" } } }`

// newImportEdgeGenerator returns a Generator over importEdgeSchema.
func newImportEdgeGenerator(t *testing.T, outDir string) *Generator {
	t.Helper()
	dir := t.TempDir()
	schemaPath := filepath.Join(dir, "schema.graphql")
	cfgPath := filepath.Join(dir, "config.jsonc")
	if err := os.WriteFile(schemaPath, []byte(importEdgeSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(cfgPath, []byte(importEdgeConfig), 0o644); err != nil {
		t.Fatal(err)
	}
	if outDir == "" {
		outDir = filepath.Join(dir, "out")
	}
	g, err := New(&Config{SchemaPath: schemaPath, ConfigPath: cfgPath, OutputDir: outDir, PackageName: "edge", ModulePath: "example.com/edge"})
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return g
}

// TestScalarImportsDeduplicatedAndSorted pins the scalars/ import list: one
// entry per package, sorted (it used to follow map iteration order).
func TestScalarImportsDeduplicatedAndSorted(t *testing.T) {
	g := newImportEdgeGenerator(t, "")
	for i := 0; i < 5; i++ { // map iteration order varies run to run
		got := buildSchemaScalarMap(g.schema, g.clientConfig.Bindings).Imports
		if !slices.Equal(got, []string{"time"}) {
			t.Fatalf("scalar imports = %q, want [time]", got)
		}
	}
}

// TestInputImportsSkipPlaceholderFields pins that the inputs/ import set
// mirrors the fields actually rendered.
func TestInputImportsSkipPlaceholderFields(t *testing.T) {
	g := newImportEdgeGenerator(t, "")
	if got := g.collectInputTypeImports(); len(got) != 0 {
		t.Errorf("input imports = %q, want none (the only scalar field is the `_` placeholder)", got)
	}
}

// TestTypeImportsIgnoreInterfaceFields pins that interface fields (never
// rendered) contribute no imports to types/.
func TestTypeImportsIgnoreInterfaceFields(t *testing.T) {
	g := newImportEdgeGenerator(t, "")
	got := g.collectTypeImports()
	if slices.Contains(got, "example.com/edge/"+pkgEnums) {
		t.Errorf("type imports = %q, must not include enums/ (only Lonely's unrendered field uses it)", got)
	}
	if !slices.Contains(got, "time") {
		t.Errorf("type imports = %q, want time (Ev.at / Ev.d)", got)
	}
}

// generatedBanner is the Go convention tools use to recognise generated
// files (https://go.dev/s/generatedcode); it must be the first line.
var generatedBanner = regexp.MustCompile(`^// Code generated .* DO NOT EDIT\.$`)

// TestImportEdgeSDKCompiles is the build gate for the three traps above, and
// checks that EVERY generated Go file starts with the gqlkit banner
// (header.tmpl used to say "Code generated by ent"; builder.go,
// graphqlclient.go and batch.go had no banner at all).
func TestImportEdgeSDKCompiles(t *testing.T) {
	work := t.TempDir()
	t.Chdir(work)
	outDir := filepath.Join(work, "out")
	if err := newImportEdgeGenerator(t, outDir).Generate(); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	err := filepath.WalkDir(outDir, func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".go") {
			return err
		}
		src, rerr := os.ReadFile(p)
		if rerr != nil {
			return rerr
		}
		first, _, _ := strings.Cut(string(src), "\n")
		if !generatedBanner.MatchString(first) || !strings.Contains(first, "gqlkit") {
			t.Errorf("%s: first line %q is not the gqlkit generated-code banner", p, first)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}

	requireGoToolchain(t)
	if err := os.WriteFile(filepath.Join(outDir, "go.mod"), []byte("module example.com/edge\n\ngo 1.23\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, err := goBuild(t, outDir, "./..."); err != nil {
		t.Fatalf("edge SDK does not compile: %v\n%s", err, out)
	}
}

// TestMinimalSchemaSDKCompiles covers the empty end of every dimension: no
// objects, inputs, enums, custom scalars or mutations — just one scalar
// query. Every generated package must still be valid Go (empty types/,
// inputs/, enums/ files; no mutations/ dir).
func TestMinimalSchemaSDKCompiles(t *testing.T) {
	work := t.TempDir()
	t.Chdir(work)
	schemaPath := filepath.Join(work, "schema.graphql")
	if err := os.WriteFile(schemaPath, []byte("type Query { ping: String }\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	outDir := filepath.Join(work, "out")
	g, err := New(&Config{SchemaPath: schemaPath, OutputDir: outDir, PackageName: "mini", ModulePath: "example.com/mini"})
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	if err := g.Generate(); err != nil {
		t.Fatalf("Generate: %v", err)
	}
	if _, err := os.Stat(filepath.Join(outDir, pkgMutations)); !os.IsNotExist(err) {
		t.Errorf("mutations/ generated for a schema without a Mutation root (stat err = %v)", err)
	}

	requireGoToolchain(t)
	if err := os.WriteFile(filepath.Join(outDir, "go.mod"), []byte("module example.com/mini\n\ngo 1.23\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if out, err := goBuild(t, outDir, "./..."); err != nil {
		t.Fatalf("minimal SDK does not compile: %v\n%s", err, out)
	}
}
