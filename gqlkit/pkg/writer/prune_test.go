// writeRaw writes a file under dir without going through a Writer.
func writeRaw(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// exists reports whether rel exists under dir.
func exists(dir, rel string) bool {
	_, err := os.Lstat(filepath.Join(dir, filepath.FromSlash(rel)))
	return err == nil
}

// TestPruneOwnershipMatrix enumerates what Prune may and may not delete. Only
// a regular file whose FIRST line is exactly BannerLine and that the current
// run did not write is stale; every near miss must survive.
func TestPruneOwnershipMatrix(t *testing.T) {
	dir := t.TempDir()
	keep := map[string]string{
		"hand.go":            "package sdk\n\nfunc Mine() {}\n",
		"notes.md":           "# notes\n",
		"banner_second.go":   "package sdk\n" + BannerLine + "\n",
		"other_tool.go":      "// Code generated by ent, DO NOT EDIT.\n\npackage sdk\n",
		"trailing_space.go":  BannerLine + " \n\npackage sdk\n",
		"prefix_text.go":     "x" + BannerLine + "\n",
		"empty.go":           "",
		"long_first_line.go": BannerLine + string(make([]byte, 400)) + "\n",
		"mixed/hand.go":      "package mixed\n", // keeps mixed/ although mixed/old.go goes
	}
	stale := map[string]string{
		"types/old.go":      GeneratedHeader + "package types\n",
		"queries/q_old.go":  GeneratedHeader + "package queries\n",
		"crlf.go":           BannerLine + "\r\n\r\npackage sdk\r\n",
		"no_newline.go":     BannerLine,
		"deep/a/b/c/old.go": GeneratedHeader + "package c\n",
		"old.txt":           BannerLine + "\nnot go but ours\n",
		"mixed/old.go":      GeneratedHeader + "package mixed\n",
	}
	// Directories this prune empties (removed) vs. ones it must keep.
	emptiedDirs := []string{"deep/", "deep/a/", "deep/a/b/", "deep/a/b/c/", "queries/"}
	keptDirs := []string{"types", "mixed", "already_empty"}
	if err := os.MkdirAll(filepath.Join(dir, "already_empty"), 0o755); err != nil {
		t.Fatal(err)
	}
	for rel, c := range keep {
		writeRaw(t, dir, rel, c)
	}
	for rel, c := range stale {
		writeRaw(t, dir, rel, c)
	}
	// A symlink to a stale-looking file is never followed or removed.
	if err := os.Symlink(filepath.Join(dir, "types", "old.go"), filepath.Join(dir, "link.go")); err != nil {
		t.Fatal(err)
	}

	w := NewWriter(dir)
	// Written by "this run": must survive although it carries the banner.
	if err := w.WriteFile("types/types.go", GeneratedHeader+"package types\n"); err != nil {
		t.Fatal(err)
	}

	var wantStale []string
	for rel := range stale {
		wantStale = append(wantStale, rel)
	}
	wantStale = append(wantStale, emptiedDirs...)
	slices.Sort(wantStale)

	// Dry run lists, deletes nothing.
	got, err := w.Prune(true)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(got, wantStale) {
		t.Fatalf("dry run = %q, want %q", got, wantStale)
	}
	for rel := range stale {
		if !exists(dir, rel) {
			t.Fatalf("dry run deleted %s", rel)
		}
	}
	for _, d := range emptiedDirs {
		if !exists(dir, d) {
			t.Fatalf("dry run removed dir %s", d)
		}
	}

	// Real run deletes exactly the stale set.
	got, err = w.Prune(false)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(got, wantStale) {
		t.Fatalf("prune = %q, want %q", got, wantStale)
	}
	for rel := range stale {
		if exists(dir, rel) {
			t.Errorf("stale %s survived", rel)
		}
	}
	for _, rel := range append(slices.Collect(maps.Keys(keep)), "types/types.go", "link.go") {
		if !exists(dir, rel) {
			t.Errorf("%s was deleted but must be kept", rel)
		}
	}
	for _, d := range emptiedDirs {
		if exists(dir, d) {
			t.Errorf("emptied dir %s survived", d)
		}
	}
	for _, d := range keptDirs {
		if !exists(dir, d) {
			t.Errorf("dir %s removed but must be kept", d)
		}
	}

	// Run twice: idempotent.
	if again, err := w.Prune(false); err != nil || len(again) != 0 {
		t.Errorf("second prune = %q, %v; want nothing", again, err)
	}
}

// TestPruneMissingDir: nothing to prune is not an error.
func TestPruneMissingDir(t *testing.T) {
	got, err := NewWriter(filepath.Join(t.TempDir(), "absent")).Prune(false)
	if err != nil || len(got) != 0 {
		t.Fatalf("Prune(missing) = %q, %v", got, err)
	}
}

// TestGeneratedHeaderStartsWithBanner pins the coupling Prune relies on.
func TestGeneratedHeaderStartsWithBanner(t *testing.T) {
	if GeneratedHeader != BannerLine+"\n\n" {
		t.Fatalf("GeneratedHeader %q does not start with BannerLine", GeneratedHeader)
	}
}

// TestWrittenTracksCleanedPaths pins that Written normalises paths the same
// way WriteFile records them, and that a zero-value Writer records too.
func TestWrittenTracksCleanedPaths(t *testing.T) {
	w := &Writer{outputDir: t.TempDir()}
	if err := w.WriteFile("./a/../types/x.go", "package types\n"); err != nil {
		t.Fatal(err)
	}
	if !w.Written("types/x.go") || !w.Written("types/./x.go") {
		t.Error("Written did not match the cleaned path")
	}
	if w.Written("types/y.go") {
		t.Error("Written reported a file that was never written")
	}
}
