#!/bin/sh
# Runs every example-cli script and checks what it produced. Exits non-zero
# on the first failed check. Needs mockapi running (task mockapi:run) and the
# npm packages installed (npm install in example-cli/).
set -eu

. "$(dirname -- "$0")/lib.sh"

LOG_DIR=$OUT_DIR/logs
mkdir -p "$LOG_DIR"
failures=0

pass() { echo "  ok    $1"; }
fail() {
	echo "  FAIL  $1" >&2
	failures=$((failures + 1))
}

# check DESCRIPTION COMMAND...: passes when the command succeeds.
check() {
	desc=$1
	shift
	if "$@" >/dev/null 2>&1; then pass "$desc"; else fail "$desc"; fi
}

# check_not DESCRIPTION COMMAND...: passes when the command fails.
check_not() {
	desc=$1
	shift
	if "$@" >/dev/null 2>&1; then fail "$desc"; else pass "$desc"; fi
}

# run_script NAME: runs one example, keeps its output in LOG_DIR/NAME.log.
run_script() {
	echo "== $1"
	if "$EXAMPLE_DIR/$1" >"$LOG_DIR/$1.log" 2>&1; then
		pass "$1 exited 0"
	else
		fail "$1 exited non-zero (see $LOG_DIR/$1.log)"
		tail -n 20 "$LOG_DIR/$1.log" >&2
		return 1
	fi
}

require_endpoint

S=$OUT_DIR/schema
if run_script fetch-and-filter.sh; then
	check "full.graphql has the Query type" grep -q '^type Query {' "$S/full.graphql"
	check "full.json is an introspection result" grep -q '"__schema"' "$S/full.json"
	check "trimmed keeps todo" grep -q '^  todo(id: ID!): Todo' "$S/trimmed.graphql"
	check_not "trimmed drops ping" grep -q '^  ping:' "$S/trimmed.graphql"
	check_not "trimmed prunes TodoConnection" grep -q '^type TodoConnection' "$S/trimmed.graphql"
	check "no-todos keeps ping" grep -q '^  ping:' "$S/no-todos.graphql"
	check_not "no-todos drops todos" grep -q '^  todos(' "$S/no-todos.graphql"
	check_not "no-todos drops createTodo" grep -q '^  createTodo(' "$S/no-todos.graphql"
	check "--debug printed a curl command" grep -q '^curl ' "$S/curl.txt"
	check "--debug carried the -H header" grep -q "Authorization: Bearer example-token" "$S/curl.txt"
fi

if run_script generate-go.sh; then
	check "Go program printed ping" grep -q '^ping: ' "$LOG_DIR/generate-go.sh.log"
	check "Go program printed todos" grep -q '^todo ' "$LOG_DIR/generate-go.sh.log"
	check_not "go.mod has no gqlkit requirement" grep -q 'gqlkit/gqlkit' "$OUT_DIR/go-app/go.mod"
	check "DateTime bound to time.Time" grep -q 'DateTime = time.Time' "$OUT_DIR/go-app/sdk/scalars/scalars.go"
	check "Metadata fell back to any" grep -q 'Metadata = any' "$OUT_DIR/go-app/sdk/scalars/scalars.go"
	# --prune: a stale generated file goes, a hand-written file stays.
	(
		cd "$OUT_DIR/go-app"
		printf '// Code generated by gqlkit. DO NOT EDIT.\n\npackage queries\n' >sdk/queries/query_removed.go
		printf 'package queries\n\n// Hand-written: no banner, never pruned.\n' >sdk/queries/helpers.go
		"$BIN_DIR/gqlkit" generate -s schema.graphql -o ./sdk -m example.com/cliapp/sdk \
			-c "$EXAMPLE_DIR/go.config.jsonc" --prune >"$LOG_DIR/prune.log" 2>&1
	)
	check "--prune reported the stale file" grep -q '^Pruned: queries/query_removed.go' "$LOG_DIR/prune.log"
	check_not "--prune deleted the stale file" test -f "$OUT_DIR/go-app/sdk/queries/query_removed.go"
	check "--prune kept the hand-written file" test -f "$OUT_DIR/go-app/sdk/queries/helpers.go"
	rm -f "$OUT_DIR/go-app/sdk/queries/helpers.go"
fi

if run_script generate-ts.sh; then
	check "TS program printed ping" grep -q '^ping: ' "$LOG_DIR/generate-ts.sh.log"
	check "TS program printed todos with decoded dates" grep -q '^todo .* created 20' "$LOG_DIR/generate-ts.sh.log"
	check "JSON re-exported from type-fest" grep -q 'JsonValue as JSON } from "type-fest"' "$OUT_DIR/ts-app/sdk/scalars/index.ts"
	# The narrowing guarantee: reading a field that was not selected must not
	# compile. Write a copy that reads t.done and expect tsc to reject it.
	sed 's|for (const t of todos) {|for (const t of todos) { console.log(t.done);|' \
		"$OUT_DIR/ts-app/main.ts" >"$OUT_DIR/ts-app/unselected.ts"
	check "reading an unselected field fails tsc with TS2339" \
		sh -c "cd '$EXAMPLE_DIR' && npx tsc --noEmit -p . | grep -q 'unselected.ts.*TS2339'"
	rm -f "$OUT_DIR/ts-app/unselected.ts"
	check "DateTime codec re-exported" grep -q 'decodeDate' "$OUT_DIR/ts-app/sdk/scalars/index.ts"
	check "SDK uses .js relative imports" grep -q 'from "../builder/index.js"' "$OUT_DIR/ts-app/sdk/queries/todos.ts"
	# Node ESM: the same sources must type-check under nodenext as an ES module.
	echo '{ "type": "module" }' >"$OUT_DIR/ts-app/package.json"
	check "SDK type-checks as Node ESM (nodenext)" \
		sh -c "cd '$EXAMPLE_DIR' && npx tsc -p tsconfig.nodenext.json"
	rm -f "$OUT_DIR/ts-app/package.json"
fi

if run_script multi-file-schema.sh; then
	check "query from user.graphql generated" test -f "$OUT_DIR/multi-file/sdk/queries/query_user.go"
	check "query from post.graphql generated" test -f "$OUT_DIR/multi-file/sdk/queries/query_posts.go"
fi

echo "== failure modes"
check_not "a header without a colon is rejected" \
	"$BIN_DIR/gqlkit-sdl" fetch --url "$GRAPHQL_URL" -H "NoColon" -o "$OUT_DIR/never.graphql"
check_not "a missing schema file is rejected" \
	"$BIN_DIR/gqlkit" generate -s "$OUT_DIR/missing.graphql" -o "$OUT_DIR/never-sdk"
check_not "an unquoted glob (extra arguments) is rejected" \
	"$BIN_DIR/gqlkit" generate -s "$OUT_DIR/multi-file/schema/post.graphql" "$OUT_DIR/multi-file/schema/user.graphql" -o "$OUT_DIR/never-sdk"
check_not "a missing -c file is rejected" \
	"$BIN_DIR/gqlkit" generate -s "$S/full.graphql" -o "$OUT_DIR/never-sdk" -m example.com/x/never-sdk -c "$OUT_DIR/missing.jsonc"
check_not "--dry-run without --prune is rejected" \
	"$BIN_DIR/gqlkit" generate -s "$S/full.graphql" -o "$OUT_DIR/never-sdk" -m example.com/x/never-sdk --dry-run
check_not "an introspection JSON file is not accepted as --schema" \
	"$BIN_DIR/gqlkit" generate -s "$S/full.json" -o "$OUT_DIR/never-sdk"
check_not "scripts refuse to run with no server" \
	env GRAPHQL_URL=http://127.0.0.1:9/query "$EXAMPLE_DIR/fetch-and-filter.sh"

echo
if [ "$failures" -ne 0 ]; then
	echo "example-cli: $failures check(s) failed" >&2
	exit 1
fi
echo "example-cli: all checks passed"
